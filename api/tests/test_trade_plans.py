def test_plan_payload_has_no_fill_price():
    """The field that forced people to invent a fill is gone.

    The old form required `price` to save anything, so recording a plan meant
    typing an execution price for a trade that had not executed. One real plan
    was saved with actual_entry equal to its take-profit for that reason.
    """
    assert "price" not in main.PlanCreate.model_fields
    assert "exit_price" not in main.PlanCreate.model_fields
    assert "execution_time" not in main.PlanCreate.model_fields


def test_a_plan_needs_only_a_ticker_and_a_side():
    """A bias is worth recording before the prices are decided."""
    plan = main.PlanCreate(ticker="nvda", direction="buy")
    assert plan.ticker == "NVDA"
    assert plan.planned_entry is None


def test_long_and_short_are_stored_as_buy_and_sell():
    """Four spellings for two concepts is how a query silently misses rows."""
    assert main.PlanCreate(ticker="X", direction="LONG").direction == "BUY"
    assert main.PlanCreate(ticker="X", direction="short").direction == "SELL"


def test_a_side_that_is_neither_is_refused():
    with pytest.raises(ValidationError):
        main.PlanCreate(ticker="X", direction="HOLD")


def test_planned_r_is_not_a_client_input():
    """It is generated by Postgres from entry, stop and target.

    Accepting it here would let the stated R disagree with the three numbers it
    claims to summarise -- which is what happens when an edit to the stop
    forgets to recompute.
    """
    assert "planned_r" not in main.PlanCreate.model_fields
    assert "planned_r" not in main.PlanUpdate.model_fields


def test_planned_r_column_is_database_generated():
    """`Computed` is what makes SQLAlchemy omit it from INSERT and UPDATE.

    Without it every write sends a value Postgres rejects outright, because a
    generated column cannot be assigned.
    """
    assert main.PlannedTrade.__table__.c.planned_r.computed is not None


# ---------------------------------------------------------------------------
# Attaching: one plan, every fill of the leg
# ---------------------------------------------------------------------------


def test_every_fill_in_the_leg_gets_the_plan():
    """An 11-fill entry is one trade, not eleven unplanned ones."""
    plan = make_plan()
    fills = [make_fill(entry_date=NOW + timedelta(seconds=i)) for i in range(11)]

    main._apply_plan_to_fills(plan, fills)

    assert all(f.plan_id == plan.id for f in fills)
    assert plan.status == main.PLAN_ATTACHED


def test_journal_values_land_on_the_earliest_fill_only():
    """Prices on one row; risk on one row above all.

    risk_amount is absolute, not per-share. Copied onto all seven fills of a
    position, anything that summed it would report seven times the risk that
    was actually taken.
    """
    plan = make_plan()
    early = make_fill(entry_date=NOW)
    late = make_fill(entry_date=NOW + timedelta(minutes=1))

    copied = main._apply_plan_to_fills(plan, [early, late])

    assert early.planned_entry == Decimal("336.00")
    assert early.stop_loss == Decimal("328.60")
    assert early.target == Decimal("345.00")
    assert early.risk_amount == Decimal("22.20")
    assert "risk_amount" in copied

    assert late.planned_entry is None
    assert late.risk_amount is None
    # ...but the link is still on both, so provenance survives whichever fill
    # FIFO later treats as the opener.
    assert late.plan_id == plan.id


def test_take_profit_lands_in_the_column_the_ledger_reads():
    """The plan calls it take_profit; the ledger has always called it target."""
    plan = make_plan()
    fill = make_fill()
    main._apply_plan_to_fills(plan, [fill])
    assert fill.target == Decimal("345.00")


def test_an_existing_value_is_never_overwritten():
    """A filled-in field was either edited by hand or copied by an earlier
    attach. Nothing distinguishes those, so the safe reading is that it is
    yours."""
    plan = make_plan()
    fill = make_fill(stop_loss=Decimal("330.00"), thesis="my own note")

    copied = main._apply_plan_to_fills(plan, [fill])

    assert fill.stop_loss == Decimal("330.00")
    assert fill.thesis == "my own note"
    assert "stop_loss" not in copied
    assert "thesis" not in copied


def test_risk_percent_rides_on_risk_amount_being_absent():
    """risk_percent carries a column default of 1.00, so it is never NULL and
    cannot tell a sized trade from an unsized one. risk_amount has no default,
    which makes it the only honest gate."""
    plan = make_plan()
    already_sized = make_fill(risk_amount=Decimal("50.00"), risk_percent=Decimal("2.00"))

    main._apply_plan_to_fills(plan, [already_sized])

    assert already_sized.risk_amount == Decimal("50.00")
    assert already_sized.risk_percent == Decimal("2.00")


def test_attaching_nothing_is_a_no_op():
    """A plan whose leg came back empty must not be marked ATTACHED."""
    plan = make_plan()
    assert main._apply_plan_to_fills(plan, []) == []
    assert plan.status == main.PLAN_OPEN


