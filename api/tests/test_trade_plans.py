# Slippage reads the same way on both sides
# ---------------------------------------------------------------------------


def test_paying_more_than_planned_is_adverse_on_a_long():
    assert main._entry_slippage("BUY", Decimal("336.00"), Decimal("337.10")) == pytest.approx(-1.10)


def test_paying_less_than_planned_is_favourable_on_a_long():
    assert main._entry_slippage("BUY", Decimal("336.00"), Decimal("335.00")) == pytest.approx(1.00)


def test_a_short_filled_higher_is_favourable():
    """The sign has to flip with the side.

    Selling short above your planned entry is a better price for the same
    trade. A raw `actual - planned` would read correctly on longs and
    backwards on every short -- and would do it quietly.
    """
    assert main._entry_slippage("SELL", Decimal("100.00"), Decimal("101.00")) == pytest.approx(1.00)
    assert main._entry_slippage("SELL", Decimal("100.00"), Decimal("99.00")) == pytest.approx(-1.00)


def test_slippage_needs_both_numbers():
    """An unplanned trade has no slippage -- zero would be a claim."""
    assert main._entry_slippage("BUY", None, Decimal("337.10")) is None
    assert main._entry_slippage("BUY", Decimal("336.00"), None) is None


