"""Keeping a plan and an execution from ever becoming the same row.

The bug this feature exists to kill: `trades` accepted rows from two
independent sources -- the IBKR ingest and hand entry -- and deduplicated on
`ibkr_exec_id`. A hand-logged fill (MANUAL-<uuid>) and the broker's copy of the
same execution (IBKR-<transaction_id>) had no shared identifier, so they could
never recognise each other. Planning a trade here and executing it at IBKR
produced two rows for one real trade: double the position, wrong average cost,
and phantom shares still open after the real ones were sold.

Four properties carry the weight, and each is one careless simplification away
from being a bug again:

  * A plan is not an execution. Creating one touches `planned_trades` alone,
    so nothing about it can reach P&L, win rate or exposure.
  * One plan covers EVERY fill of its opening leg. IBKR splits an order into
    several executions -- this account has an 11-fill entry -- so attaching to
    just one would describe a fraction of the position.
  * The journal values land on the earliest fill ONLY. Prices replicated across
    seven rows are merely redundant; `risk_amount` replicated across seven rows
    is wrong, because anything summing it reports seven times the real risk.
  * A plan must predate the fill it claims, and expire. Without both rules a
    forgotten setup silently claims an unrelated trade months later, and the
    mis-attribution looks exactly like the feature working.
"""

import os
import uuid
from datetime import datetime, timedelta, timezone
from decimal import Decimal
from types import SimpleNamespace

import pytest
from pydantic import ValidationError

os.environ.setdefault("CORS_ALLOW_ORIGINS", "https://trading-journal-test.vercel.app")

import main  # noqa: E402


NOW = datetime(2026, 7, 22, 14, 30, tzinfo=timezone.utc)


def make_plan(**overrides):
    """A plan shaped like the ORM object, without needing a database."""
    base = dict(
        id=uuid.uuid4(),
        ticker="PANW",
        direction="BUY",
        quantity=Decimal("3"),
        planned_entry=Decimal("336.00"),
        stop_loss=Decimal("328.60"),
        take_profit=Decimal("345.00"),
        planned_r=Decimal("1.22"),
        risk_percent=Decimal("0.89"),
        risk_amount=Decimal("22.20"),
        strategy_id=None,
        thesis="Ascending triangle, higher low.",
        status=main.PLAN_OPEN,
        created_at=NOW - timedelta(hours=2),
        updated_at=None,
    )
    base.update(overrides)
    return SimpleNamespace(**base)


def make_fill(**overrides):
    """A freshly imported broker fill: journal columns still empty."""
    base = dict(
        id=uuid.uuid4(),
        ibkr_exec_id=f"IBKR-{uuid.uuid4().hex[:8]}",
        ticker="PANW",
        direction="BUY",
        quantity=Decimal("1"),
        actual_entry=Decimal("337.10"),
        entry_date=NOW,
        planned_entry=None,
        stop_loss=None,
        target=None,
        strategy_id=None,
        thesis=None,
        # Mirrors the real column default: risk_percent is NEVER None, which is
        # exactly why it cannot be used to detect an unsized trade.
        risk_percent=Decimal("1.00"),
        risk_amount=None,
        plan_id=None,
    )
    base.update(overrides)
    return SimpleNamespace(**base)


