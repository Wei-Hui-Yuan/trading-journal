def test_hand_added_fills_are_labelled_not_hidden():
    """A hand-typed price is an assertion and should look like one next to
    figures the broker vouched for."""
    assert main.EXEC_PREFIX_REPAIR == "REPAIR-"
    assert main.EXEC_PREFIX_BROKER == "IBKR-"
    assert "has_hand_added_fills" in main.RoundTripOut.model_fields


def test_the_sync_reports_plans_it_attached():
    """The moment the two halves of the journal meet is worth a line."""
    result = main.IngestResult(
        executions_parsed=3, staged_new=3, staged_duplicates=0,
        trades_created=3, trades_duplicates=0, positions_matched=0,
        symbols_touched=["PANW"], skipped_non_tradeable=0, plans_attached=1,
    )
    assert result.plans_attached == 1


def test_plans_attached_defaults_to_zero():
    """Older callers constructing a result without it must not break."""
    result = main.IngestResult(
        executions_parsed=0, staged_new=0, staged_duplicates=0,
        trades_created=0, trades_duplicates=0, positions_matched=0,
        symbols_touched=[], skipped_non_tradeable=0,
    )
    assert result.plans_attached == 0


